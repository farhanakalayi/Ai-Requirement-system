// Export and formatting utilities

export function exportToJson(data, filename = "requirement-analysis-report.json") {
  const jsonStr = JSON.stringify(data, null, 2);
  const blob = new Blob([jsonStr], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function generateMarkdownReport(data) {
  const title = data.title || "AI Requirement Analysis Report";
  const date = data.createdAt ? new Date(data.createdAt).toLocaleString() : new Date().toLocaleString();
  const summary = data.analysis?.summary || {};
  const reqs = data.analysis?.requirements || (Array.isArray(data.analysis) ? data.analysis : []);
  const risks = data.analysis?.risks || [];
  const recs = data.analysis?.recommendations || [];

  let md = `# ${title}\n`;
  md += `*Generated by Requirement AI SaaS on ${date}*\n\n`;

  md += `## 1. Executive Summary\n`;
  md += `- **Total Requirements:** ${summary.total || reqs.length}\n`;
  md += `- **High Priority:** ${summary.high || 0}\n`;
  md += `- **Medium Priority:** ${summary.medium || 0}\n`;
  md += `- **Low Priority:** ${summary.low || 0}\n`;
  md += `- **Clarity / Quality Score:** ${summary.clarityScore || 85}/100\n`;
  md += `- **Risks & Ambiguities Identified:** ${risks.length}\n\n`;

  md += `## 2. Prioritized Requirements Specification\n\n`;
  md += `| ID | Priority | Category | Classification | Requirement |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- |\n`;
  reqs.forEach((r, idx) => {
    const id = r.id || `REQ-${String(idx + 1).padStart(3, "0")}`;
    const prio = r.priority || "Low";
    const cat = r.category || "General";
    const cls = r.classification || "Functional";
    const cleanText = (r.requirement || "").replace(/\|/g, "\\|");
    md += `| **${id}** | **${prio}** | ${cat} | ${cls} | ${cleanText} |\n`;
  });
  md += `\n`;

  if (risks.length > 0) {
    md += `## 3. Risk & Ambiguity Analysis\n\n`;
    risks.forEach((r, idx) => {
      md += `### ${idx + 1}. [${r.severity || "Moderate"}] ${r.type}: "${r.term || ""}"\n`;
      md += `- **Requirement:** ${r.requirement}\n`;
      md += `- **Issue:** ${r.description}\n`;
      md += `- **Why It Matters:** ${r.whyItMatters}\n`;
      md += `- **Suggested Improvement:** ${r.suggestion}\n\n`;
    });
  }

  if (recs.length > 0) {
    md += `## 4. Actionable Recommendations\n\n`;
    recs.forEach((rec, idx) => {
      md += `${idx + 1}. **[${rec.priority || "Medium"}] ${rec.title}**: ${rec.description}\n`;
    });
    md += `\n`;
  }

  md += `---\n*Generated by Requirement AI Analyzer*`;
  return md;
}

export function formatRelativeTime(dateString) {
  if (!dateString) return "";
  try {
    const now = new Date();
    const date = new Date(dateString);
    const diffSec = Math.floor((now - date) / 1000);

    if (diffSec < 60) return "Just now";
    const diffMin = Math.floor(diffSec / 60);
    if (diffMin < 60) return `${diffMin}m ago`;
    const diffHour = Math.floor(diffMin / 60);
    if (diffHour < 24) return `${diffHour}h ago`;
    const diffDay = Math.floor(diffHour / 24);
    if (diffDay === 1) return "Yesterday";
    if (diffDay < 7) return `${diffDay}d ago`;
    return date.toLocaleDateString(undefined, { month: "short", day: "numeric" });
  } catch {
    return "";
  }
}
